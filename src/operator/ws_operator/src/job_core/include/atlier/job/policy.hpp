// 운영 정책 — 흐름이 갈라지는 곳의 기본값.
//
// **이 헤더가 값의 원본이다.** job_manager 의 YAML 은 이 구조체를 ROS 파라미터로
// 노출한 사본일 뿐이므로, 의미가 바뀌면 여기 주석을 먼저 고친다.
//
// 값 하나하나가 BRD·Process Flow 의 문장에 대응한다 — 근거 없는 값은 두지 않는다.
#ifndef ATLIER_JOB_POLICY_HPP
#define ATLIER_JOB_POLICY_HPP

namespace atlier::job
{

struct Policy
{
  // ── F8.1 중간 모니터링 ────────────────────────────────────────────────────
  /// 중간 확인을 켤 것인가. SA 는 ⑤ 드로잉 모니터링을 `이후`로 두었으므로
  /// MVP(sim First Stroke)에서는 false 로 끄고 완주시킨다.
  bool review_enabled{true};

  /// 전체 스트로크의 몇 지점에서 확인하는가. **작업당 1회만** 발동한다 —
  /// 스트로크마다 촬영하면 자세 이동(F8.3) 때문에 N2(15분)를 넘긴다.
  double review_at_ratio{0.5};

  /// 사람이 응답하지 않을 때 몇 초를 기다리는가.
  ///
  /// ⚠️ **이 값만 문서에 근거가 없는 신규 값이다.** 업무목록 미결 "AC1 과 F8.1 의
  /// 양립 해석" 중 ①(무응답 시 자동 계속 = 비개입)을 구현으로 옮긴 것이다.
  /// 확인 대기 동안 로봇은 서 있으므로 이 시간은 그대로 N2 예산을 먹는다.
  double review_timeout_s{60.0};

  /// 무응답일 때의 기본 동작. true = 계속(해석 ①), false = 중단.
  bool review_default_continue{true};

  // ── F8.2 완성작 촬영 ──────────────────────────────────────────────────────
  /// 완료 직전 촬영 단계를 거칠 것인가. MuJoCo 에는 카메라가 없어(PF §5.1)
  /// 시뮬 완주 검증에서는 false 로 끈다. AC3 판정에는 필요하다.
  bool capture_enabled{true};

  // ── F4.4 스트로크 실패 ────────────────────────────────────────────────────
  /// Phase 1 은 **기록 후 계속, 재시도 없음**(PF §3.2). 재시도 횟수는 구현 단계
  /// 파라미터로 유보된 항목이라 자리만 두었다 — 상태 머신은 아직 쓰지 않는다.
  int stroke_retry_count{0};

  // ── 정지 시 펜 처리 (PF §3.4 표) ──────────────────────────────────────────
  /// F6.5 일시정지는 pen-up 후 멈춘다. 펜이 닿은 채 서면 심이 한 점에 눌려
  /// 점(blob)이 남고 재개해도 사라지지 않는다. 테이프 고정이라 z 완충이 없어
  /// 이 위험은 더 크다 (BRD R2).
  bool pen_up_on_pause{true};

  /// F6.4 긴급정지는 pen-up 없이 즉시 멈춘다. 어차피 작업을 폐기하므로
  /// blob 을 신경 쓸 이유가 없고, N4 는 "즉시 반영"을 요구한다.
  bool pen_up_on_estop{false};

  /// 값이 성립하지 않으면 std::invalid_argument 를 던진다.
  void Validate() const;
};

// **동시 작업은 1건이다.** BRD 부록 B 가 "다중 작업 큐"를 Phase 3(무인 연속 운전)
// 으로 미뤘으므로 큐·스케줄러는 이 모듈에 없다. 작업 하나가 종료 상태에 닿아야
// 다음 작업이 시작된다 — 이 전제가 깨지면 상태 머신부터 다시 봐야 한다.

}  // namespace atlier::job

#endif  // ATLIER_JOB_POLICY_HPP
